package gen

import (
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const (
	grammarPath       = "suppress/grammar_gen.go"
	suppressionPage   = "contract/grammar/suppression.md"
	symbolRefPage     = "contract/grammar/symbol-ref.md"
	directiveSection  = "### The shape"
	blocksSection     = "### Building blocks"
	perFormSection    = "### One expression per form"
	directiveCount    = 3
	grammarTableCells = 3
)

// grammarSource writes the suppress package's grammar data: the directive's
// shape and the three expressions suppression.md's decision procedure applies,
// and one expression per row of symbol-ref.md's per-form table with every
// building block substituted.
func grammarSource(fsys fs.FS, out map[string][]byte) error {
	suppression, err := fs.ReadFile(fsys, suppressionPage)
	if err != nil {
		return err
	}
	shape, expressions, err := directiveGrammar(string(suppression))
	if err != nil {
		return fmt.Errorf("%s: %w", suppressionPage, err)
	}
	symbolRef, err := fs.ReadFile(fsys, symbolRefPage)
	if err != nil {
		return err
	}
	forms, err := referenceForms(string(symbolRef))
	if err != nil {
		return fmt.Errorf("%s: %w", symbolRefPage, err)
	}
	w := &writer{}
	w.f("// Code generated by deadset-gen from the Contract's grammar pages. DO NOT EDIT.\n\npackage suppress\n\n")
	w.f("// The directive's shape and the three expressions suppression.md's decision procedure applies to a comment, in order.\n")
	w.f("const (\n\tdirectiveShape = %s\n", strconv.Quote(shape))
	for i, name := range []string{"directiveCandidate", "directiveWellFormed", "directiveReasonless"} {
		w.f("\t%s = %s\n", name, strconv.Quote(expressions[i]))
	}
	w.f(")\n\n// referenceForms is one expression per row of symbol-ref.md's per-form table, every building block substituted, in the page's order.\nvar referenceForms = []referenceForm{\n")
	for _, form := range forms {
		w.f("\t{language: %s, expression: %s},\n", strconv.Quote(form.language), strconv.Quote(form.expression))
	}
	w.f("}\n")
	src, err := format.Source([]byte(w.b.String()))
	if err != nil {
		return fmt.Errorf("%s: %w", grammarPath, err)
	}
	out[grammarPath] = src
	return nil
}

// directiveGrammar is the shape line, the first fence of the shape section, and
// the section's one-line fences that open with the comment's solidi.
func directiveGrammar(page string) (shape string, expressions []string, err error) {
	section, err := pageSection(page, directiveSection)
	if err != nil {
		return "", nil, err
	}
	fences := pageFences(section)
	if len(fences) == 0 || len(fences[0]) != 1 {
		return "", nil, errors.New(directiveSection + " opens with no one-line shape")
	}
	for _, fence := range fences {
		if len(fence) == 1 && strings.HasPrefix(fence[0], "^//") {
			expressions = append(expressions, fence[0])
		}
	}
	if len(expressions) != directiveCount {
		return "", nil, fmt.Errorf("%s publishes %d expressions, want %d", directiveSection, len(expressions), directiveCount)
	}
	return fences[0][0], expressions, compiles(expressions)
}

// grammarForm is one row of the per-form table, expanded.
type grammarForm struct{ language, expression string }

// referenceForms expands every row of the per-form table.
func referenceForms(page string) ([]grammarForm, error) {
	blocks, err := grammarRows(page, blocksSection)
	if err != nil {
		return nil, err
	}
	rows, err := grammarRows(page, perFormSection)
	if err != nil {
		return nil, err
	}
	forms := make([]grammarForm, 0, len(rows))
	expressions := make([]string, 0, len(rows))
	for _, row := range rows {
		expression, err := expandBlocks(row[2], blocks)
		if err != nil {
			return nil, err
		}
		forms = append(forms, grammarForm{language: row[0], expression: expression})
		expressions = append(expressions, expression)
	}
	return forms, compiles(expressions)
}

// grammarRows is a section's table below its header row, each code span
// unwrapped.
func grammarRows(page, heading string) ([][]string, error) {
	section, err := pageSection(page, heading)
	if err != nil {
		return nil, err
	}
	rows := tableRows(section)
	if len(rows) < 2 {
		return nil, fmt.Errorf("%s carries no table row below its header", heading)
	}
	for _, row := range rows[1:] {
		if len(row) != grammarTableCells {
			return nil, fmt.Errorf("%s row %q holds %d cells, want %d", heading, row, len(row), grammarTableCells)
		}
		for i := range row {
			row[i] = strings.TrimSuffix(strings.TrimPrefix(row[i], "`"), "`")
		}
	}
	return rows[1:], nil
}

// expandBlocks substitutes every block's expression for its name, to a fixed
// point, since a block may be written from others.
func expandBlocks(expression string, blocks [][]string) (string, error) {
	for range len(blocks) + 1 {
		before := expression
		for _, block := range blocks {
			expression = strings.ReplaceAll(expression, block[0], block[1])
		}
		if expression == before {
			return expression, nil
		}
	}
	return "", fmt.Errorf("substituting the building blocks into %q does not settle", expression)
}

// compiles refuses an expression Go's regexp does not compile, which no
// product could apply.
func compiles(expressions []string) error {
	for _, expression := range expressions {
		if _, err := regexp.Compile(expression); err != nil {
			return err
		}
	}
	return nil
}

// pageSection is every line after a heading the page carries once, up to the
// next heading of any level.
func pageSection(page, heading string) (string, error) {
	lines := strings.Split(page, "\n")
	n := slices.Index(lines, heading)
	if n < 0 || slices.Contains(lines[n+1:], heading) {
		return "", fmt.Errorf("the page carries %q other than once", heading)
	}
	body := lines[n+1:]
	if end := slices.IndexFunc(body, func(line string) bool { return strings.HasPrefix(line, "#") }); end >= 0 {
		body = body[:end]
	}
	return strings.Join(body, "\n"), nil
}

// pageFences is the lines of every fenced block, in page order.
func pageFences(text string) [][]string {
	var fences [][]string
	open := -1
	for line := range strings.SplitSeq(text, "\n") {
		switch {
		case strings.HasPrefix(line, "```") && open >= 0:
			open = -1
		case strings.HasPrefix(line, "```"):
			fences, open = append(fences, nil), len(fences)
		case open >= 0:
			fences[open] = append(fences[open], line)
		}
	}
	return fences
}

// tableRows is the cells of every table row, the delimiter row dropped and an
// escaped pipe read as a pipe.
func tableRows(text string) [][]string {
	var rows [][]string
	for line := range strings.SplitSeq(text, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "|") {
			continue
		}
		fields := strings.Split(strings.Trim(strings.ReplaceAll(trimmed, `\|`, "\x00"), "|"), "|")
		cells := make([]string, 0, len(fields))
		delimiter := true
		for _, field := range fields {
			cell := strings.ReplaceAll(strings.TrimSpace(field), "\x00", "|")
			delimiter = delimiter && cell != "" && strings.Trim(cell, "-:") == ""
			cells = append(cells, cell)
		}
		if !delimiter {
			rows = append(rows, cells)
		}
	}
	return rows
}

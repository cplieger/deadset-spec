const vocabPath = "vocab/vocab_gen.go"

// The documents vocab_gen.go is written from beside kinds.json, decoded only as
// far as the package carries them.
type (
	exemptionsDoc struct {
		Exemptions []struct {
			RetainsKinds map[string][]string `json:"retains_kinds"`
			Class        string              `json:"class"`
			Confidence   string              `json:"confidence"`
			Languages    []string            `json:"languages"`
		} `json:"exemptions"`
	}
	exitCodesDoc struct {
		ExitCodes []struct {
			Name string `json:"name"`
			Code int    `json:"code"`
		} `json:"exit_codes"`
		FailureClasses struct {
			Setup struct {
				Prefix  string `json:"prefix"`
				Classes []struct {
					Class     string   `json:"class"`
					Languages []string `json:"languages"`
				} `json:"classes"`
			} `json:"setup"`
			Run struct {
				Prefix  string `json:"prefix"`
				Classes []struct {
					Class    string   `json:"class"`
					Products []string `json:"products"`
				} `json:"classes"`
			} `json:"run"`
		} `json:"failure_classes"`
	}
	contractDoc struct {
		ContractVersion string   `json:"contract_version"`
		SchemaVersions  []string `json:"schema_versions"`
	}
	confidenceDoc struct {
		Evidence []evidenceRow `json:"evidence"`
	}
	corpusDoc struct {
		CorpusVersion string `json:"corpus_version"`
	}
	cliDoc struct {
		Options []struct {
			Option     string `json:"option"`
			Value      string `json:"value"`
			Setting    string `json:"setting"`
			Summary    string `json:"summary"`
			Repeatable bool   `json:"repeatable"`
		} `json:"options"`
		Products []struct {
			Role  string          `json:"role"`
			Verbs json.RawMessage `json:"verbs"`
		} `json:"products"`
		AnalyzerVerbs []struct {
			Options map[string][]string `json:"options"`
			verbRow
		} `json:"analyzer_verbs"`
	}
	verbRow struct {
		Verb      string   `json:"verb"`
		Summary   string   `json:"summary"`
		Stdout    string   `json:"stdout"`
		Options   []string `json:"options"`
		ExitCodes []int    `json:"exit_codes"`
	}
	configDoc struct {
		Properties struct {
			Reporters struct {
				Properties struct {
					Formats struct {
						Items struct {
							Enum []string `json:"enum"`
						} `json:"items"`
					} `json:"formats"`
				} `json:"properties"`
			} `json:"reporters"`
		} `json:"properties"`
	}
)

// vocabDocs is every document vocab_gen.go is written from.
type vocabDocs struct {
	corpus     corpusDoc
	kinds      kindsDoc
	exits      exitCodesDoc
	contract   contractDoc
	exemptions exemptionsDoc
	confidence confidenceDoc
	languages  languagesDoc
	cli        cliDoc
	config     configDoc
}

// writer appends formatted Go source.
type writer struct{ b strings.Builder }

func (w *writer) f(layout string, args ...any) { fmt.Fprintf(&w.b, layout, args...) }

// vocabSource writes the vocab package's data from the Contract's documents.
func vocabSource(fsys fs.FS, out map[string][]byte) error {
	var d vocabDocs
	for name, into := range map[string]any{
		kindsPath: &d.kinds, exemptionsPath: &d.exemptions, "contract/exit-codes.json": &d.exits,
		"contract/contract.json": &d.contract, "contract/confidence.json": &d.confidence, "corpus/corpus.json": &d.corpus,
		configSource: &d.config, languagesPath: &d.languages, cliPath: &d.cli,
	} {
		data, err := fs.ReadFile(fsys, name)
		if err != nil {
			return err
		}
		if err := json.Unmarshal(data, into); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	if len(d.contract.SchemaVersions) == 0 {
		return errors.New("contract/contract.json: no schema_versions")
	}
	w := &writer{}
	w.f("// Code generated by deadset-gen from the Contract's documents. DO NOT EDIT.\n\npackage vocab\n\n")
	d.versions(w)
	if err := d.kindRows(w); err != nil {
		return err
	}
	if err := d.symbolKinds(w); err != nil {
		return err
	}
	d.exemptionRows(w)
	d.exitRows(w)
	if err := d.commandLine(w); err != nil {
		return err
	}
	src, err := format.Source([]byte(w.b.String()))
	if err != nil {
		return fmt.Errorf("%s: %w", vocabPath, err)
	}
	out[vocabPath] = src
	return nil
}

// versions writes the versions, the languages and the closed value lists.
func (d *vocabDocs) versions(w *writer) {
	w.f("// The versions this module states: of the Contract, of the newest report schema it admits, and of the conformance corpus.\nconst (\n")
	w.f("ContractVersion = %q\n", d.contract.ContractVersion)
	w.f("SchemaVersion = %q\n", d.contract.SchemaVersions[len(d.contract.SchemaVersions)-1])
	w.f("CorpusVersion = %q\n", d.corpus.CorpusVersion)
	w.f("Prefix = %q\n)\n\n", d.kinds.Prefix)
	w.f("var schemaVersions = %s\n\n", goStrings(d.contract.SchemaVersions))
	ids := make([]string, 0, len(d.languages.Languages))
	w.f("// The languages the vocabularies name.\nconst (\n")
	for i := range d.languages.Languages {
		l := d.languages.Languages[i].Language
		ids = append(ids, l)
		w.f("%s Language = %q\n", languageIdent(l), l)
	}
	w.f(")\n\nvar languages = %s\n\n", goConsts("Language", ids, languageIdent))
	writeConsts(w.f, "subjects a finding is about", "Subject", "Subject", d.kinds.Subjects, ident)
	writeConsts(w.f, "reachability classes, from the most to the least certain", "Class", "", d.kinds.ReachabilityClasses, ident)
	writeConsts(w.f, "severities a configuration may give a kind", "Severity", "", d.kinds.Severities, ident)
	writeConsts(w.f, "fixabilities a finding may carry", "Fixability", "", d.kinds.Fixabilities, ident)
	writeConsts(w.f, "renderings reporters.formats may name", "Format", "Format", d.config.Properties.Reporters.Properties.Formats.Items.Enum, formatIdent)
}

// kindRows writes the code constants, the kind rows and the families.
func (d *vocabDocs) kindRows(w *writer) error {
	w.f("// The live issue kinds.\nconst (\n")
	for i := range d.kinds.Kinds {
		w.f("%s Code = %q\n", ident(d.kinds.Kinds[i].Name), d.kinds.Kinds[i].Code)
	}
	w.f(")\n\nvar kinds = []Kind{\n")
	for i := range d.kinds.Kinds {
		if err := d.kindRow(w, &d.kinds.Kinds[i]); err != nil {
			return err
		}
	}
	w.f("}\n\nvar families = []Family{\n")
	keyLength := 0
	for i := range d.kinds.Ranges {
		r := &d.kinds.Ranges[i]
		key := familyKey(r)
		if keyLength != 0 && len(key) != keyLength {
			return fmt.Errorf("%s: the range %s to %s has a family key of another length", kindsPath, r.Start, r.End)
		}
		keyLength = len(key)
		w.f("{Key: %q, Name: %q, Title: %q, Question: %q, Status: %q},\n", key, r.Family, r.Title, r.Question, r.Status)
	}
	w.f("}\n\n// FamilyKeyLength is the length of a key naming a whole family.\nconst FamilyKeyLength = %d\n\n", keyLength)
	return nil
}

// familyKey is the key naming one range's family: what every code of the range
// starts with, the part its first and last code share.
func familyKey(r *rangeRow) string {
	n := 0
	for n < len(r.Start) && n < len(r.End) && r.Start[n] == r.End[n] {
		n++
	}
	return r.Start[:n]
}

// kindRow writes one kind's literal, each optional member only where set.
func (d *vocabDocs) kindRow(w *writer, k *kindDoc) error {
	details, err := detailsSource(k.Details)
	if err != nil {
		return fmt.Errorf("%s: %s: %w", kindsPath, k.Code, err)
	}
	w.f("{\nCode: %s,\nName: %q,\nLanguages: %s,\nSubject: %s,\nHoldsLive: %t,\nRule: %s,\n",
		ident(k.Name), k.Name, goConsts("Language", k.Languages, languageIdent), "Subject"+ident(k.Subject), k.HoldsLive, strconv.Quote(k.Rule))
	if k.Precondition != "" {
		w.f("Precondition: %s,\n", strconv.Quote(k.Precondition))
	}
	if details != "" {
		w.f("Details: %s,\n", details)
	}
	w.f("DefaultEnabled: %t,\nDefaultSeverity: %s,\nMaxClass: %s,\nFixability: %s,\n", k.DefaultEnabled, ident(k.DefaultSeverity), ident(k.MaxClass), ident(k.Fixability))
	if len(k.FindingFixability) > 0 {
		w.f("FindingFixabilities: %s,\n", goConsts("Fixability", k.FindingFixability, ident))
	}
	if len(k.Overlap) > 0 {
		w.f("Overlap: map[Language][]string{\n")
		for _, l := range sortedKeys(k.Overlap) {
			w.f("%s: %s,\n", languageIdent(l), goStrings(k.Overlap[l]))
		}
		w.f("},\n")
	}
	if len(k.DerivedFrom) > 0 {
		w.f("DerivedFrom: %s,\n", goConsts("Code", k.DerivedFrom, codeIdent(d.kinds.Kinds)))
	}
	w.f("Fixed: %t,\n},\n", k.Fixed)
	return nil
}

// symbolKinds writes each symbol kind's subject and the kinds' order.
func (d *vocabDocs) symbolKinds(w *writer) error {
	symbolKinds, err := parse(d.kinds.SymbolKinds)
	if err != nil {
		return fmt.Errorf("%s: symbol_kinds: %w", kindsPath, err)
	}
	w.f("var symbolKinds = map[string]Subject{\n")
	for _, name := range symbolKinds.keys {
		w.f("%q: Subject%s,\n", name, ident(symbolKinds.fields[name].str()))
	}
	w.f("}\n\nvar symbolKindOrder = %s\n\n", goStrings(symbolKinds.keys))
	return nil
}

// exemptionRows writes the exemption classes and the confidence evidence table.
func (d *vocabDocs) exemptionRows(w *writer) {
	w.f("// The exemption classes, of every language.\nconst (\n")
	for i := range d.exemptions.Exemptions {
		c := &d.exemptions.Exemptions[i]
		w.f("%s Exemption = %q\n", ident(c.Class), c.Class)
	}
	w.f(")\n\nvar exemptionClasses = []ExemptionClass{\n")
	for i := range d.exemptions.Exemptions {
		c := &d.exemptions.Exemptions[i]
		w.f("{Name: %s, Languages: %s, Confidence: %s, RetainsKinds: map[Language][]string{", ident(c.Class), goConsts("Language", c.Languages, languageIdent), ident(c.Confidence))
		for _, l := range sortedKeys(c.RetainsKinds) {
			w.f("%s: %s, ", languageIdent(l), goStrings(c.RetainsKinds[l]))
		}
		w.f("}},\n")
	}
	w.f("}\n\nvar evidence = []Evidence{\n")
	for i := range d.confidence.Evidence {
		e := &d.confidence.Evidence[i]
		w.f("{Name: %q, Rule: %q, Class: %s, Languages: %s, Codes: %s},\n", e.Evidence, e.Rule, ident(e.Class), goConsts("Language", e.Languages, languageIdent), goConsts("Code", e.Codes, codeIdent(d.kinds.Kinds)))
	}
	w.f("}\n\n")
}

// exitRows writes the exit codes and the failure classes of both groups.
func (d *vocabDocs) exitRows(w *writer) {
	setup, runs := &d.exits.FailureClasses.Setup, &d.exits.FailureClasses.Run
	w.f("// The exit codes a product ends with.\nconst (\n")
	for _, e := range d.exits.ExitCodes {
		w.f("Exit%s = %d\n", ident(e.Name), e.Code)
	}
	w.f(")\n\n// The setup-failure classes.\nconst (\n")
	for _, s := range setup.Classes {
		w.f("Setup%s = %q\n", ident(s.Class), s.Class)
	}
	w.f(")\n\n// The run-failure classes.\nconst (\n")
	for _, r := range runs.Classes {
		w.f("Run%s = %q\n", ident(r.Class), r.Class)
	}
	w.f(")\n\n// SetupFailurePrefix opens the line of standard error naming one setup failure.\nconst SetupFailurePrefix = %q\n\n", setup.Prefix)
	w.f("// RunFailurePrefix opens the line of standard error naming one run failure.\nconst RunFailurePrefix = %q\n\nvar setupClasses = []SetupClass{\n", runs.Prefix)
	for _, s := range setup.Classes {
		w.f("{Name: Setup%s, Languages: %s},\n", ident(s.Class), goConsts("Language", s.Languages, languageIdent))
	}
	w.f("}\n\nvar runClasses = []RunClass{\n")
	for _, r := range runs.Classes {
		w.f("{Name: Run%s, Products: %s},\n", ident(r.Class), goStrings(r.Products))
	}
	w.f("}\n")
}

// commandLine writes cli.json's options, the kinds of value they take, the
// orchestrator's verbs and the analyzers' verbs.
func (d *vocabDocs) commandLine(w *writer) error {
	var kinds []string
	for _, o := range d.cli.Options {
		if !slices.Contains(kinds, o.Value) {
			kinds = append(kinds, o.Value)
		}
	}
	w.f("\n// The kinds of value an option takes.\nconst (\n")
	for _, kind := range kinds {
		w.f("OptionValue%s OptionValue = %q\n", ident(kind), kind)
	}
	w.f(")\n\nvar options = []Option{\n")
	for _, o := range d.cli.Options {
		w.f("{Name: %q, Value: OptionValue%s, Setting: %q, Summary: %q, Repeatable: %t},\n", o.Option, ident(o.Value), o.Setting, o.Summary, o.Repeatable)
	}
	w.f("}\n\nvar orchestratorVerbs = []Verb{\n")
	for _, p := range d.cli.Products {
		if p.Role != "orchestrator" {
			continue
		}
		var verbs []verbRow
		if err := json.Unmarshal(p.Verbs, &verbs); err != nil {
			return fmt.Errorf("contract/cli.json: the orchestrator's verbs: %w", err)
		}
		for _, v := range verbs {
			w.f("{%s, Options: %s},\n", v.common(), goStrings(v.Options))
		}
	}
	w.f("}\n\nvar analyzerVerbs = []analyzerVerb{\n")
	for _, v := range d.cli.AnalyzerVerbs {
		w.f("{Verb: Verb{%s}, Options: map[Language][]string{", v.common())
		for _, l := range sortedKeys(v.Options) {
			w.f("%s: %s, ", languageIdent(l), goStrings(v.Options[l]))
		}
		w.f("}},\n")
	}
	w.f("}\n")
	return nil
}

// common is the members of a Verb literal every row of cli.json gives alike.
func (v *verbRow) common() string {
	codes := make([]string, len(v.ExitCodes))
	for i, code := range v.ExitCodes {
		codes[i] = strconv.Itoa(code)
	}
	return fmt.Sprintf("Name: %q, Summary: %q, Stdout: %q, ExitCodes: []int{%s}", v.Verb, v.Summary, v.Stdout, strings.Join(codes, ", "))
}

// writeConsts writes one typed constant per value of a closed list, and the
// list itself.
func writeConsts(w func(string, ...any), what, typ, prefix string, values []string, spell func(string) string) {
	w("// The %s.\nconst (\n", what)
	for _, v := range values {
		w("%s%s %s = %q\n", prefix, spell(v), typ, v)
	}
	plural := strings.ToLower(typ[:1]) + typ[1:] + "Values"
	w(")\n\nvar %s = %s\n\n", plural, goConsts(typ, values, func(v string) string { return prefix + spell(v) }))
}

// detailsSource is a kind's details as a Go []Detail literal, its members in
// name order, and empty for none.
func detailsSource(details map[string]any) (string, error) {
	if len(details) == 0 {
		return "", nil
	}
	var b strings.Builder
	b.WriteString("[]Detail{")
	for _, member := range sortedKeys(details) {
		switch p := details[member].(type) {
		case []any:
			languages := make([]string, 0, len(p))
			for _, l := range p {
				s, ok := l.(string)
				if !ok {
					return "", fmt.Errorf("details.%s: a language that is no string", member)
				}
				languages = append(languages, s)
			}
			fmt.Fprintf(&b, "{Member: %q, Presence: Presence{Languages: %s}}, ", member, goConsts("Language", languages, languageIdent))
		case string:
			switch p {
			case presenceRequired:
				fmt.Fprintf(&b, "{Member: %q, Presence: Presence{Required: true}}, ", member)
			case "optional":
				fmt.Fprintf(&b, "{Member: %q, Presence: Presence{Optional: true}}, ", member)
			default:
				return "", fmt.Errorf("details.%s: unknown presence %q", member, p)
			}
		default:
			return "", fmt.Errorf("details.%s: a presence that is neither a string nor a list", member)
		}
	}
	b.WriteString("}")
	return b.String(), nil
}

// ident is a vocabulary value spelled as a Go identifier: each hyphenated word
// capitalised.
func ident(s string) string {
	var b strings.Builder
	for word := range strings.SplitSeq(s, "-") {
		if word != "" {
			b.WriteString(strings.ToUpper(word[:1]) + word[1:])
		}
	}
	return b.String()
}

// languageIdent spells a language id as a Go identifier: a short id with no
// vowel is an initialism (ts, js), any other a word (go, proto).
func languageIdent(l string) string {
	if len(l) <= 3 && !strings.ContainsAny(l, "aeiou") {
		return strings.ToUpper(l)
	}
	return ident(l)
}

// formatIdent spells a format name as a Go identifier, an initialism or a
// product name in the case Go writes it.
func formatIdent(f string) string {
	if spelled, ok := map[string]string{"json": "JSON", "sarif": "SARIF", "github": "GitHub"}[f]; ok {
		return spelled
	}
	return ident(f)
}

// codeIdent spells a code as the constant its kind's name gives it.
func codeIdent(rows []kindDoc) func(string) string {
	return func(code string) string {
		for i := range rows {
			if rows[i].Code == code {
				return ident(rows[i].Name)
			}
		}
		return strconv.Quote(code)
	}
}

func goStrings(values []string) string {
	return goConsts("string", values, strconv.Quote)
}

func goConsts(typ string, values []string, spell func(string) string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = spell(v)
	}
	return "[]" + typ + "{" + strings.Join(parts, ", ") + "}"
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

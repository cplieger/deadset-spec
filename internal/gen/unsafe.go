package gen

import (
	"fmt"
	"go/format"
	"io/fs"
	"strconv"
	"strings"
)

const (
	unsafePath    = "segment/unsafe_gen.go"
	unsafeSection = "### The unsafe set"
)

// unsafeSource writes the segment package's test for symbol-ref.md's unsafe
// set, one range per row of the section's table.
func unsafeSource(fsys fs.FS, out map[string][]byte) error {
	page, err := fs.ReadFile(fsys, symbolRefPage)
	if err != nil {
		return err
	}
	ranges, err := unsafeRanges(string(page))
	if err != nil {
		return fmt.Errorf("%s: %w", symbolRefPage, err)
	}
	w := &writer{}
	w.f("// Code generated by deadset-gen from the Contract's grammar pages. DO NOT EDIT.\n\npackage segment\n\n")
	w.f("// unsafeRanges is symbol-ref.md's unsafe set, one inclusive range per row of its table, in the page's order.\n")
	w.f("var unsafeRanges = [...][2]rune{\n")
	for _, r := range ranges {
		w.f("\t{%#04x, %#04x},\n", r[0], r[1])
	}
	w.f("}\n")
	src, err := format.Source([]byte(w.b.String()))
	if err != nil {
		return fmt.Errorf("%s: %w", unsafePath, err)
	}
	out[unsafePath] = src
	return nil
}

// unsafeRanges reads the table of the unsafe-set section: each row's first and
// last code point, written U+ and four or more uppercase hexadecimal digits,
// in ascending order with no overlap.
func unsafeRanges(page string) ([][2]rune, error) {
	rows, err := grammarRows(page, unsafeSection)
	if err != nil {
		return nil, err
	}
	ranges := make([][2]rune, 0, len(rows))
	for _, row := range rows {
		var r [2]rune
		for i, cell := range row[:2] {
			hex, ok := strings.CutPrefix(cell, "U+")
			n, err := strconv.ParseUint(hex, 16, 21)
			if !ok || err != nil || len(hex) < 4 || strings.ToUpper(hex) != hex {
				return nil, fmt.Errorf("%s row %q: %q is no code point written U+XXXX", unsafeSection, row, cell)
			}
			r[i] = rune(n)
		}
		if r[1] < r[0] || len(ranges) > 0 && r[0] <= ranges[len(ranges)-1][1] {
			return nil, fmt.Errorf("%s row %q is out of order", unsafeSection, row)
		}
		ranges = append(ranges, r)
	}
	return ranges, nil
}
